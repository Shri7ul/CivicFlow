"""Centralized SQLAlchemy declarative base and shared column helpers."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    DateTime,
    JSON,
    MetaData,
    Text,
    TypeDecorator,
    Uuid,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column
from sqlalchemy.types import UserDefinedType

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base with deterministic constraint names for Alembic."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {
        dict[str, Any]: JSON().with_variant(JSONB(), "postgresql"),
    }


class UUIDPrimaryKeyMixin:
    """UUID primary key generated by the application."""

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4
    )


class TimestampMixin:
    """UTC timestamps with database-side defaults."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


def jsonb_column_type() -> JSON:
    """Use JSONB on PostgreSQL and plain JSON on portable test dialects."""
    return JSON().with_variant(JSONB(), "postgresql")


def point_geography_type() -> "PortableGeography":
    """WGS84 point geography with explicit indexes, not implicit ones."""
    return PortableGeography(geometry_type="POINT", srid=4326)


def geometry_type(geometry_type_name: str = "GEOMETRY") -> "PortableGeometry":
    """WGS84 geometry (point/line/polygon) with explicit indexes."""
    return PortableGeometry(geometry_type=geometry_type_name, srid=4326)


class _PostGISGeography(UserDefinedType):
    cache_ok = True

    def __init__(self, geometry_type: str, srid: int) -> None:
        self.geometry_type_name = geometry_type
        self.srid = srid

    def get_col_spec(self, **kw) -> str:
        return f"geography({self.geometry_type_name},{self.srid})"

    def bind_expression(self, bindvalue):
        return func.ST_GeogFromText(bindvalue)

    def column_expression(self, colexpr):
        # Return portable WKT to the application instead of PostGIS EWKB.
        return func.ST_AsText(colexpr)

    def copy(self, **kw):
        return self.__class__(self.geometry_type_name, self.srid)

    def adapt(self, cls, **kw):
        return self.__class__(self.geometry_type_name, self.srid)


class _PostGISGeometry(UserDefinedType):
    cache_ok = True

    def __init__(self, geometry_type: str, srid: int) -> None:
        self.geometry_type_name = geometry_type
        self.srid = srid

    def get_col_spec(self, **kw) -> str:
        return f"geometry({self.geometry_type_name},{self.srid})"

    def bind_expression(self, bindvalue):
        return func.ST_GeomFromText(bindvalue, self.srid)

    def column_expression(self, colexpr):
        return func.ST_AsText(colexpr)

    def copy(self, **kw):
        return self.__class__(self.geometry_type_name, self.srid)

    def adapt(self, cls, **kw):
        return self.__class__(self.geometry_type_name, self.srid)


class _PortableSpatial(TypeDecorator):
    """Compile native PostGIS types on PostgreSQL; use TEXT on SQLite tests.

    GeoAlchemy2's DDL event listeners are deliberately avoided: spatial indexes
    are declared explicitly in the models and Alembic migration. This keeps the
    PostgreSQL DDL native while allowing isolated SQLite structural tests.
    """

    impl = Text
    cache_ok = True
    _geo_cls: type = _PostGISGeometry

    def __init__(self, geometry_type: str, srid: int = 4326) -> None:
        super().__init__()
        self.geometry_type_name = geometry_type
        self.srid = srid

    def load_dialect_impl(self, dialect):
        if dialect.name == "postgresql":
            return dialect.type_descriptor(
                self._geo_cls(self.geometry_type_name, self.srid)
            )
        return dialect.type_descriptor(Text())

    def process_bind_param(self, value, dialect):
        return value

    def process_result_value(self, value, dialect):
        return value


class PortableGeography(_PortableSpatial):
    _geo_cls = _PostGISGeography
    cache_ok = True


class PortableGeometry(_PortableSpatial):
    _geo_cls = _PostGISGeometry
    cache_ok = True
